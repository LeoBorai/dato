#[cfg(test)]
mod tests {
    use super::*;
    use crate::sql::{TokenKind, split_statements_with, tokenize_with};

    fn split(src: &str) -> Vec<&str> {
        split_statements_with(src, &RULES)
    }

    #[test]
    fn list_is_sorted_for_binary_search() {
        assert!(KEYWORDS.windows(2).all(|w| w[0] < w[1]));
    }

    #[test]
    fn dollar_quoted_bodies_are_one_statement() {
        assert_eq!(
            split("do $$ begin perform 1; perform 2; end $$; select 1"),
            ["do $$ begin perform 1; perform 2; end $$", "select 1"]
        );
        assert_eq!(
            split("select $a$ it's; $$ fine $a$; select 2"),
            ["select $a$ it's; $$ fine $a$", "select 2"]
        );
    }

    #[test]
    fn parameters_are_not_dollar_quotes() {
        assert_eq!(split("select $1; select $2"), ["select $1", "select $2"]);
    }

    #[test]
    fn unterminated_dollar_quote_is_open() {
        let toks = tokenize_with("select $$ abc", &RULES);
        assert!(!toks.last().unwrap().terminated);
    }

    #[test]
    fn backslash_is_literal_but_escape_strings_escape() {
        assert_eq!(
            split("select 'a\\'; select 1"),
            ["select 'a\\'", "select 1"]
        );
        assert_eq!(
            split("select E'it\\'s; fine'; select 1"),
            ["select E'it\\'s; fine'", "select 1"]
        );
    }

    #[test]
    fn block_comments_nest() {
        let src = "select 1 /* a /* b */ ; c */;";
        assert_eq!(split(src), ["select 1 /* a /* b */ ; c */"]);
        let kinds: Vec<_> = tokenize_with(src, &RULES)
            .into_iter()
            .map(|t| t.kind)
            .collect();
        assert!(kinds.contains(&TokenKind::BlockComment));
    }

    #[test]
    fn double_quotes_are_identifiers_and_hash_is_not_a_comment() {
        let toks = tokenize_with("\"x\" # y", &RULES);
        assert_eq!(toks[0].kind, TokenKind::QuotedIdent);
        assert!(toks.iter().all(|t| t.kind != TokenKind::LineComment));
    }
}
